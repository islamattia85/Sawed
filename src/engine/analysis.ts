export interface BandRow {
  band: Band;
  /** kWh imported while this band applied. */
  kwh: number;
  /** Euro paid for that energy. */
  cost: number;
  /** Hours of the year in this band. */
  hours: number;
  /** Effective price paid, euro/kWh. */
  effectiveRate: number;
}

/**
 * Import cost split by tariff band. This is the mechanism behind a
 * recommendation: a plan wins because of when the home draws power, and this
 * shows how much of the bill falls in each window.
 */
export function bandBreakdown(sim: HourlySim): BandRow[] {
  const acc = new Map<Band, { kwh: number; cost: number; hours: number }>();
  for (let i = 0; i < HOURS_IN_YEAR; i += 1) {
    const band = (sim.band?.[i] ?? 'day') as Band;
    const cur = acc.get(band) ?? { kwh: 0, cost: 0, hours: 0 };
    cur.kwh += sim.grid_import[i] ?? 0;
    cur.cost += sim.cost[i] ?? 0;
    cur.hours += 1;
    acc.set(band, cur);
  }
  return [...acc.entries()]
    .map(([band, v]) => ({
      band,
      kwh: v.kwh,
      cost: v.cost,
      hours: v.hours,
      effectiveRate: v.kwh > 0 ? v.cost / v.kwh : 0,
    }))
    .filter((r) => r.kwh > 0.5)
    .sort((a, b) => b.cost - a.cost);
}

export interface BatteryStats {
  capacity: number;
  /** kWh in and out across the year. */
  charged: number;
  discharged: number;
  /** Full equivalent cycles: throughput divided by usable capacity. */
  equivalentCycles: number;
  /** Round-trip efficiency actually achieved, 0-1. */
  roundTripEfficiency: number;
  /** Hours the battery sat at or near full, and at or near empty. */
  hoursFull: number;
  hoursEmpty: number;
  /** Share of the year the battery was doing nothing. */
  idleShare: number;
}

/**
 * How hard the battery actually works. A battery that is full for much of the
 * summer is oversized for the load; one that is empty every evening is
 * undersized. Both are visible here and nowhere else.
 */
export function batteryStats(sim: HourlySim, capacity: number): BatteryStats | null {
  if (!(capacity > 0)) return null;
  let charged = 0;
  let discharged = 0;
  let hoursFull = 0;
  let hoursEmpty = 0;
  let idle = 0;
  for (let i = 0; i < HOURS_IN_YEAR; i += 1) {
    const c = sim.battery_charge[i] ?? 0;
    const dch = sim.battery_discharge[i] ?? 0;
    charged += c;
    discharged += dch;
    if (c < 0.01 && dch < 0.01) idle += 1;
    const soc = (sim.soc?.[i] ?? 0) / capacity;
    if (soc >= 0.97) hoursFull += 1;
    if (soc <= 0.05) hoursEmpty += 1;
  }
  return {
    capacity,
    charged,
    discharged,
    equivalentCycles: discharged / capacity,
    roundTripEfficiency: charged > 0 ? discharged / charged : 0,
    hoursFull,
    hoursEmpty,
    idleShare: idle / HOURS_IN_YEAR,
  };
}

export interface YearSummary {
  generated: number;
  consumed: number;
  selfUsed: number;
  imported: number;
  exported: number;
  /** Share of consumption met without the grid, 0-1. */
  selfSufficiency: number;
  /** Share of generation kept at home, 0-1. */
  selfConsumption: number;
  /** Yield per kWp installed, kWh. */
  specificYield: number;
  /** Best and worst month by generation. */
  bestMonth: string;
  worstMonth: string;
  /** Ratio of best to worst month generation — the seasonal swing. */
  seasonalSwing: number;
}

export function yearSummary(rows: MonthRow[], kwp: number): YearSummary {
  const tot = (k: keyof MonthRow) => rows.reduce((a, r) => a + (r[k] as number), 0);
  const generated = tot('generated');
  const consumed = tot('consumed');
  // Only the part of import that served load counts against self-sufficiency.
  const imported = tot('imported') - tot('importedToBattery');
  const sorted = [...rows].sort((a, b) => b.generated - a.generated);
  const best = sorted[0];
  const worst = sorted[sorted.length - 1];
  return {
    generated,
    consumed,
    selfUsed: tot('selfUsed'),
    imported,
    exported: tot('exported'),
    selfSufficiency: consumed > 0 ? (consumed - imported) / consumed : 0,
    selfConsumption: generated > 0 ? tot('selfUsed') / generated : 0,
    specificYield: kwp > 0 ? generated / kwp : 0,
    bestMonth: best?.month ?? '—',
    worstMonth: worst?.month ?? '—',
    seasonalSwing: worst && worst.generated > 0 ? (best?.generated ?? 0) / worst.generated : 0,
  };
}

/**
 * Hours of the year sorted by import power, descending — a load duration
 * curve for grid draw. The shape says whether a bill is driven by a few
 * extreme hours or by a broad baseline, which is what decides whether a
 * time-of-use tariff can help at all.
 */
export function importDurationCurve(sim: HourlySim, buckets = 24): number[] {
  const sorted = Array.from(sim.grid_import).sort((a, b) => b - a);
  const out: number[] = [];
  const per = Math.floor(sorted.length / buckets);
  for (let i = 0; i < buckets; i += 1) {
    let t = 0;
    for (let j = i * per; j < (i + 1) * per; j += 1) t += sorted[j] ?? 0;
    out.push(per > 0 ? t / per : 0);
  }
  return out;
}

/** Share of annual import that falls in the most expensive N% of hours. */
export function peakConcentration(sim: HourlySim, topShare = 0.1): number {
  const costs: number[] = [];
  for (let i = 0; i < HOURS_IN_YEAR; i += 1) costs.push(sim.cost[i] ?? 0);
  const total = costs.reduce((a, v) => a + v, 0);
  if (total <= 0) return 0;
  costs.sort((a, b) => b - a);
  const n = Math.max(1, Math.floor(costs.length * topShare));
  let top = 0;
  for (let i = 0; i < n; i += 1) top += costs[i] ?? 0;
  return top / total;
}
